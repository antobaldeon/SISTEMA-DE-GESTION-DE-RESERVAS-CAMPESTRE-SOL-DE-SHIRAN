CREATE TABLE cabana
(
    id_cabana         NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR2(100) NOT NULL,
    descripcion       CLOB NOT NULL,
    aforo_maximo      NUMBER(10,0) NOT NULL,
    num_habitaciones  NUMBER(10,0) NOT NULL,
    num_banos         NUMBER(10,0) NOT NULL,
    precio_base_noche NUMBER(10,2) NOT NULL,
    estado            VARCHAR2(20) DEFAULT 'ACTIVA',
    imagen_principal  VARCHAR2(255) NOT NULL,
    fecha_creacion    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE cabana_imagenes
(
    id_imagen  NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cabana  NUMBER(19,0) NOT NULL,
    url_imagen VARCHAR2(255) NOT NULL,
    CONSTRAINT fk_imagen_cabana FOREIGN KEY (id_cabana) REFERENCES cabana (id_cabana) ON DELETE CASCADE
);
CREATE TABLE cabana_comodidades
(
    id_comodidad     NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cabana        NUMBER(19,0) NOT NULL,
    nombre_comodidad VARCHAR2(50) NOT NULL,
    CONSTRAINT fk_comodidad_cabana FOREIGN KEY (id_cabana) REFERENCES cabana (id_cabana) ON DELETE CASCADE
);
CREATE TABLE reserva
(
    id_reserva            NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cabana             NUMBER(19,0) NOT NULL,
    id_usuario            NUMBER(19,0) NOT NULL,
    fecha_ingreso         DATE      NOT NULL,
    fecha_salida          DATE      NOT NULL,
    cantidad_huespedes    NUMBER(10,0) NOT NULL,
    precio_noche_aplicado NUMBER(10,2) NOT NULL,
    monto_total           NUMBER(10,2) NOT NULL,
    monto_adelanto        NUMBER(10,2) NOT NULL,
    estado_reserva        VARCHAR2(30) DEFAULT 'PENDIENTE_PAGO',
    expira_en             TIMESTAMP NOT NULL,
    fecha_creacion        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reserva_cabana FOREIGN KEY (id_cabana) REFERENCES cabana (id_cabana)
);
CREATE TABLE transaccion_pago
(
    id_transaccion      NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva          NUMBER(19,0) NOT NULL,
    id_externo_pasarela VARCHAR2(100),
    monto               NUMBER(10,2) NOT NULL,
    moneda              VARCHAR2(10) DEFAULT 'PEN',
    metodo_pago         VARCHAR2(50),
    estado_transaccion  VARCHAR2(30) DEFAULT 'PENDIENTE',
    fecha_transaccion   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva),
    CONSTRAINT uq_pago_externo UNIQUE (id_externo_pasarela)
);
CREATE TABLE webhook_log
(
    id_log                  NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion          NUMBER(19,0),
    id_transaccion_pasarela VARCHAR2(100),
    payload_json            CLOB NOT NULL,
    estado_procesamiento    VARCHAR2(30) DEFAULT 'PROCESADO_EXITO',
    fecha_recepcion         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_transaccion FOREIGN KEY (id_transaccion) REFERENCES transaccion_pago (id_transaccion)
);
